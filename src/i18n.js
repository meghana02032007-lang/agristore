const LANG_CODES = {
  English: 'en', Tamil: 'ta', Hindi: 'hi',
  Telugu: 'te', Kannada: 'kn', Malayalam: 'ml',
};

const _whNameCache = {};

export async function translateWarehouseName(name, lang) {
  if (!name || lang === 'English') return name;
  const key = `${lang}:${name}`;
  if (_whNameCache[key]) return _whNameCache[key];
  try {
    const res = await fetch('https://libretranslate.com/translate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ q: name, source: 'en', target: LANG_CODES[lang] || 'en', format: 'text' }),
    });
    const data = await res.json();
    const translated = data.translatedText || name;
    _whNameCache[key] = translated;
    return translated;
  } catch {
    return name;
  }
}

